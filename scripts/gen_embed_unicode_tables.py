    print()
    ascii_punct = lambda cp: (33 <= cp <= 47) or (58 <= cp <= 64) or (91 <= cp <= 96) or (123 <= cp <= 126)
    emit_ranges("k_punct", ranges(lambda cp: ascii_punct(cp) or cat(cp).startswith("P")))
    print()
    emit_ranges("k_control",
                ranges(lambda cp: cat(cp) in ("Cc", "Cf") and cp not in (9, 10, 13)))
    print()
    emit_ranges("k_space", ranges(lambda cp: cp in (9, 10, 13, 32) or cat(cp) == "Zs"))
    print()
    emit_ranges("k_mark", ranges(lambda cp: cat(cp) == "Mn"))
    print()
    print("static const embed_cp_map_t k_fold[] = {")
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF or 0xAC00 <= cp <= 0xD7A3 or cat(cp) == "Mn":
            continue
        c = chr(cp)
        r = fold(c)
        if r != c:
            assert 1 <= len(r) <= 3, (hex(cp), r)
            outs = ", ".join(f"0x{ord(x):05X}" for x in r) + ", 0" * (3 - len(r))
            print(f"   {{ 0x{cp:05X}, {len(r)}, {{ {outs} }} }},")
    print("};")


