def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = not (0xD800 <= cp <= 0xDFFF) and pred(cp)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def cat(cp):
    return unicodedata.category(chr(cp))


def fold(c):
    """lower -> NFD -> drop Mn, per character (the reference order)."""
    s = unicodedata.normalize("NFD", c.lower())
    return "".join(x for x in s if unicodedata.category(x) != "Mn")


def emit_ranges(name, rs):
    print(f"static const embed_cp_range_t {name}[] = {{")
    for a, b in rs:
        print(f"   {{ 0x{a:05X}, 0x{b:05X} }},")
    print("};")


